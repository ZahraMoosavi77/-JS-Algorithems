function sortedSquarredArray(array: number[]) {
  let squarArray = [];
  for (let i = 0; i < array.length; i++) {
    squarArray.push(array[i] ** 2); // T = O(n) S = O(n)
  }
  squarArray.sort((a, b) => a - b); // T = log(n)
  return squarArray; //T = nlogn
}
function sortedSquarredArray2(array: number[]) {
  let squarArray = [];
  let firstpointer = 0;
  let lastpointer = array.length - 1;
  for (let i = array.length-1; i >= 0 ; i--) {
    if (array[lastpointer] ** 2 >= array[firstpointer] ** 2) {  // T = O(n)
      squarArray[i] = array[lastpointer] ** 2;
      lastpointer--;
    } else {
      squarArray[i] = array[firstpointer] ** 2;

      // squarArray.push(array[firstpointer] ** 2);
      firstpointer++;
    }
  }
  return squarArray;
}
